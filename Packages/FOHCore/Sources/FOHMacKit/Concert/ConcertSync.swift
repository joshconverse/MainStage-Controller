import Foundation

/// The MainStage sync (PLAN.md §9c): runs Tools/concert-format/concert_write.py on the working concert in place.
/// The writer copies the concert, syncs the copy, moves the original into the backup folder and puts the copy in its
/// place, so nothing is ever deleted. It must only run while MainStage is closed; callers check.
public enum ConcertSync {
    /// What one run did, from the writer's `--report`.
    public struct Report: Codable, Hashable, Sendable {
        public struct Skip: Codable, Hashable, Sendable {
            public let strip: String
            public let role: String
            public let reason: String
        }

        /// False when the concert already matched (then nothing was touched and no backup was made).
        public let changed: Bool
        /// The previous version of the concert, when it changed.
        public let backup: String?
        public let written: Int
        public let repointed: Int
        public let removed: Int
        public let kept: Int
        public let skipped: [Skip]

        public var summary: String {
            guard changed else { return "already up to date (\(kept) assignments)" }
            var parts = ["\(written) added"]
            if repointed > 0 { parts.append("\(repointed) re-pointed") }
            if removed > 0 { parts.append("\(removed) removed") }
            parts.append("\(kept) unchanged")
            return parts.joined(separator: ", ")
        }
    }

    public enum Failure: Error, CustomStringConvertible {
        case noWriter
        case timedOut(TimeInterval)
        case failed(status: Int32, output: String)
        case noReport

        public var description: String {
            switch self {
            case .noWriter: return "the concert writer isn't installed with FOH Bridge"
            case .timedOut(let s): return "the concert writer took longer than \(Int(s)) s and was stopped"
            case .failed(let status, let output): return "the concert writer failed (\(status)): \(output)"
            case .noReport: return "the concert writer didn't report what it did"
            }
        }
    }

    public static let mainStageBundleID = "com.apple.mainstage3"
    public static let python = URL(fileURLWithPath: "/usr/bin/python3")

    /// `~/Library/Application Support/FOH Bridge/concert-backups/`
    public static func backupDirectory(_ store: BridgeStore) -> URL {
        store.directory.appendingPathComponent("concert-backups", isDirectory: true)
    }

    /// Sync `concert` with `export`. Blocks until the writer finishes; call it off the main thread.
    public static func run(_ export: AssignmentExport, concert: URL, backups: URL, writer: URL,
                           timeout: TimeInterval = 180, log: (String) -> Void = { _ in }) throws -> Report {
        try withScratch { scratch in
            let assignments = scratch.appendingPathComponent("assignments.json")
            let reportURL = scratch.appendingPathComponent("report.json")
            try JSONEncoder().encode(export).write(to: assignments)
            let result = try execute(writer: writer, ["--assignments", assignments.path, "--in-place", concert.path,
                                                      "--backup-dir", backups.path, "--report", reportURL.path],
                                     in: scratch, timeout: timeout)
            for line in result.output.split(separator: "\n") where line.hasPrefix("  note:") { log(String(line.dropFirst(2))) }
            guard let reportData = try? Data(contentsOf: reportURL) else { throw Failure.noReport }
            return try JSONDecoder().decode(Report.self, from: reportData)
        }
    }

    /// One hardware-assigned control in a concert, hand-made ones included (`concert_write.py --list-mappings`).
    public struct Mapping: Codable, Hashable, Sendable {
        /// The input's CoreMIDI unique ID, MIDI channel (1-based) and CC.
        public let source: Int?
        public let channel: Int?
        public let cc: Int?
        public let identity: String
        public let autogenerated: Bool
        /// MAPlugInParameterMapping, MABaseplateParameterMapping, WsActionParameterMapping…
        public let kind: String?
        /// Parameter number (`parameterIndex_1`), or the action number for actions.
        public let parameter: Int?
        /// Plugin insert position, 1-based (nil for channel-strip controls and actions).
        public let position: Int?
        public let strip: String?
        public let level: String?
        public let patch: String?

        enum CodingKeys: String, CodingKey {
            case source, channel, cc, identity, autogenerated, parameter, position, strip, level, patch
            case kind = "class"
        }
    }

    /// Every hardware-assigned control in the concert as saved. Read-only; safe while MainStage runs (it only sees
    /// what MainStage last saved). Blocks; call it off the main thread.
    public static func listMappings(concert: URL, writer: URL, timeout: TimeInterval = 60) throws -> [Mapping] {
        try withScratch { scratch in
            let result = try execute(writer: writer, ["--list-mappings", concert.path], in: scratch, timeout: timeout, mergeErrors: false)
            return try JSONDecoder().decode([Mapping].self, from: Data(result.output.utf8))
        }
    }

    private static func withScratch<T>(_ body: (URL) throws -> T) throws -> T {
        let scratch = FileManager.default.temporaryDirectory.appendingPathComponent("foh-concert-sync-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: scratch, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: scratch) }
        return try body(scratch)
    }

    /// Run the writer with `/usr/bin/python3 -I` and wait for it. Throws on a timeout or a failing exit status.
    private static func execute(writer: URL, _ arguments: [String], in directory: URL, timeout: TimeInterval,
                                mergeErrors: Bool = true) throws -> (output: String, errors: String) {
        guard FileManager.default.fileExists(atPath: writer.path) else { throw Failure.noWriter }
        let process = Process()
        process.executableURL = python
        // -I: ignore the user's Python environment and the current directory (the writer finds its own modules).
        process.arguments = ["-I", writer.path] + arguments
        process.currentDirectoryURL = directory
        let output = Pipe(), errors = mergeErrors ? output : Pipe()
        process.standardOutput = output
        process.standardError = errors
        let done = DispatchSemaphore(value: 0)
        process.terminationHandler = { _ in done.signal() }
        try process.run()
        // Read while it runs, so a chatty writer can't fill a pipe and stall.
        var outData = Data(), errData = Data()
        let group = DispatchGroup()
        group.enter()
        DispatchQueue(label: "foh.concert-sync.stdout").async { outData = output.fileHandleForReading.readDataToEndOfFile(); group.leave() }
        if !mergeErrors {
            group.enter()
            DispatchQueue(label: "foh.concert-sync.stderr").async { errData = errors.fileHandleForReading.readDataToEndOfFile(); group.leave() }
        }
        if done.wait(timeout: .now() + timeout) == .timedOut {
            process.terminate()   // the writer cleans up its scratch copy; the concert swap itself can't be interrupted
            _ = done.wait(timeout: .now() + 10)
            throw Failure.timedOut(timeout)
        }
        group.wait()
        let out = String(decoding: outData, as: UTF8.self), err = String(decoding: errData, as: UTF8.self)
        guard process.terminationStatus == 0 else {
            let tail = (mergeErrors ? out : err).split(separator: "\n").suffix(4).joined(separator: " · ")
            throw Failure.failed(status: process.terminationStatus, output: tail)
        }
        return (out, err)
    }
}
