#!/usr/bin/env python3
"""Write FOH Remote's MIDI assignments straight into a COPY of a MainStage concert.

    fohctl assignments --out assignments.json           # what to write, from the running FOH Bridge
    concert_write.py --assignments assignments.json SRC.concert DST.concert [--strips in/1,in/2] [--dry-run]
    concert_write.py --assignments assignments.json --in-place CONCERT.concert --backup-dir DIR
    concert_write.py --list-mappings CONCERT.concert      # every hardware-assigned control, as JSON

For every bound role this does what one Assign & Map does (see CONCERT_FORMAT.md):
  - a hidden, autogenerated screen control (a new UUID identity) and, in workspace.layout, its
    WsInvisibleScreenControl model, hardware input (bridge port, channel, CC), "Send Value to" (the bridge's
    same-named destination, outputEnabled) and the layout's own null-mapping and UI-data records,
  - the mapping to the plugin / channel-strip parameter, in the patch's data.plist AND in the patch's
    mapping table inside one channel strip's .cst (MainStage loads mappings from the .cst; with only the
    data.plist copy it drops the assignment),
  - the empty UI-data record in the patch and concert data.plist.
It is a sync, not just an append: addresses already assigned are kept when their mapping matches, re-pointed
when it doesn't (a plugin moved slot), and hidden controls on the plugin ports ("FOH Plugins …") that nothing
wants any more are removed. Assignments on the other ports are never removed: they may be the user's own.
It never touches SRC and refuses to overwrite DST. --in-place writes a hidden sibling copy, moves the original
into --backup-dir and puts the copy in its place, so nothing is deleted.
"""
