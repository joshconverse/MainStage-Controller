def controller(port, channel, cc, value, kind):
    """kind: 'input' (layout hardware input), 'output' ("Send Value to"), 'event' (the mapping's learned event)."""
    if kind == "event":
        type_, bits, steps, cc_out = -3, 31, 2147483648, cc
    elif kind == "output":
        type_, bits, steps, cc_out = 5, 7, 128, SEND_VALUE_CC
    else:
        type_, bits, steps, cc_out = 5, 7, 128, cc
    return Obj("WsMutableController", CONTROLLER_CHAIN, {
        "timeStamp": Ref(0), "mb3": 0, "controllerTag": NULL, "maxValue": 127, "isBaseplate": False,
        "channelID": channel, "type": type_, "minValue": 0, "value": value if kind != "output" else 0,
        "MIDIPort": port, "controllerID": cc_out, "bits": bits, "steps": steps})


def mapping(cls, *, inst, chan, param, slot=None, flipped=False, send_mute=False, saved=None, event=None):
    """One mapping object, field for field as MainStage 4.3 archives it (see the LMF Gain example)."""
    has_saved, saved_float, saved_double = saved or (False, 0.0, 0.0)
    chain = {"plugin": PLUGIN_CHAIN, "bypass": BYPASS_CHAIN, "baseplate": BASEPLATE_CHAIN}[cls]
    f = {"kSavedValueFloatKey": saved_float}
    if cls != "baseplate":
        f["slot"] = Ref(slot)
    f["kHasSavedValueKey"] = has_saved
    if cls == "baseplate":
        f["isSendMuteMapping"] = send_mute
    f.update({"parameterIndex_1": Ref(param), "kFilterMappingKey": False, "rangeIsFlipped": flipped, "kDisplayIndexKey": 0,
              "momentaryType": False, "inputControlEvent": event, "kGInstIDKey": inst, "wasAutoset": False})
    if cls != "baseplate":
        f["isMIDIPlugIn"] = False
    f.update({"channelID": chan, "takeVelocity": False, "kSavedValueDoubleKey": saved_double,
              "kRangeMappingModeKey": Ref(1 if flipped else 0), "rangeHigh": Ref(-1),
              "kDisplayParameterValueAsPercentageKey": False, "kDiscreteStepsKey": False, "kIsNewSavedValueKey": True,
              "kMappingCreatedFromSmartMapKey": False, "rangeLow": Ref(-1)})
    return Obj(chain[0], chain, f)


