CLASS_OF = {"plugin": "MAPlugInParameterMapping", "bypass": "MABypassParameterMapping",
            "baseplate": "MABaseplateParameterMapping", "action": "WsActionParameterMapping"}


def spec_of(m):
    """What an existing mapping drives, comparable with a wanted (class, param, slot, inst, flipped) spec."""
    if m is None:
        return None
    if m.cls == CLASS_OF["action"]:
        return (m.cls, ref_value(m.fields.get("actionIndex")), None, None, False)
    return (m.cls, ref_value(m.fields.get("parameterIndex_1")), ref_value(m.fields.get("slot")),
            m.fields.get("kGInstIDKey"), bool(m.fields.get("rangeIsFlipped")))


def target_of(row, channel_info, strip_key=""):
    """(class, param, slot, flipped, send_mute) for a role row, or raise Skip. Class "action" carries the action
    number in `param`."""
    t = row["target"]
    if strip_key.startswith("master/") and t == "mute":
        return "action", MASTER_MUTE_ACTION, None, False, False   # the Master strip has no mute of its own
    if strip_key.startswith("master/") and t == "solo":
        raise Skip("the Master strip has no solo")
    if t == "record":
        if not strip_key.startswith("master/"):
            raise Skip("Record is a MainStage action; it goes on the Master strip")
        return "action", RECORD_ACTION, None, False, False
    if t == "plugin":
        try:
            param = int(row["parameterID"])
        except ValueError:
            raise Skip("parameter %r isn't an AU parameter ID" % row["parameterID"])
        return "plugin", param, row["pluginPosition"] - 1, False, False
    if t == "bypass":
        slot = row["pluginPosition"] - 1
        return "bypass", BYPASS_BASE + slot, slot, False, False   # 127 = bypassed, as the bridge sends it
    if t in BASEPLATE:
        return "baseplate", BASEPLATE[t], None, False, False
    if t in ("sendLevel", "sendMute"):
        bus = row.get("bus")
        if bus is None:
            raise Skip("send has no MainStage bus")
        sends = channel_info.get("Channel_sends") or []
        slot = next((i + 1 for i, s in enumerate(sends) if isinstance(s, dict) and s.get("sendOutputIndex") == bus - 1), None)
        if slot is None:
            raise Skip("Bus %d isn't sent from this strip in MainStage" % bus)
        if t == "sendLevel":
            return "baseplate", SEND_LEVEL_BASE + slot, None, False, False
        return "baseplate", SEND_MUTE_BASE + slot, None, True, True   # role is "send on"; MainStage's is mute
    raise Skip("unknown target %r" % t)


def saved_value_for(patch, cls, inst, slot, param, send_mute, flipped):
    """Copy the saved value of an existing mapping to the same parameter, so loading the copy changes nothing.
    Only from a mapping in the same direction: a flipped button's saved value would invert ours."""
    for m in patch.mappings():
        if m.cls == "MABypassParameterMapping":
            kind = "bypass"
        elif m.cls == "MAPlugInParameterMapping":
            kind = "plugin"
        elif m.cls == "MABaseplateParameterMapping":
            kind = "baseplate"
        else:
            continue
        if kind != cls or m.fields.get("kGInstIDKey") != inst or ref_value(m.fields.get("parameterIndex_1")) != param:
            continue
        if cls != "baseplate" and ref_value(m.fields.get("slot")) != slot:
            continue
        if cls == "baseplate" and bool(m.fields.get("isSendMuteMapping")) != send_mute:
            continue
        if bool(m.fields.get("rangeIsFlipped")) != flipped:
            continue
        if m.fields.get("kHasSavedValueKey"):
            return True, m.fields.get("kSavedValueFloatKey", 0.0), m.fields.get("kSavedValueDoubleKey", 0.0)
    return None


# A channel strip file's first chunk names the strip's kind and number (byte 4 and the u16 at 6 of its payload).
# Paired with MAChannelID across Apple's bundled concerts: kind → MAChannelID type. The index is the strip's number,
# which held for every aux, instrument, output and master, and for Church.concert's audio strips (Lead vox 1,
# Guitar 2). Kind 0x44 (Church.concert's mono "Output 1"/"Output 2") appears in no example, so it isn't guessed.
STRIP_KINDS = {0x40: (0, "audio"), 0x42: (8, "aux"), 0x43: (2, "instrument"), 0x46: (7, "master"), 0x4C: (6, "output")}


def strip_kind(cst_path):
    """(kind byte, number) from a .cst's header, or None."""
    try:
        payload = ChannelStripFile(cst_path).chunks[0][1]
        return payload[4], struct.unpack_from("<H", payload, 6)[0]
    except Exception:
        return None


def channel_id_for(patch, inst, position, cst_path=None):
    """The strip's MAChannelID: copied from an existing mapping to it when there is one, else derived from its .cst
    header (see STRIP_KINDS). Returns ((type, index, alias), how) or raises Skip for a strip kind not seen yet."""
    for m in patch.mappings():
        if m.fields.get("kGInstIDKey") == inst and isinstance(m.fields.get("channelID"), Obj):
            c = m.fields["channelID"]
            return (ref_value(c.fields.get("type")), ref_value(c.fields.get("index")), ref_value(c.fields.get("aliasIndex"))), "existing mapping"
    header = strip_kind(cst_path) if cst_path else None
    if header is None:
        return (0, position + 1, 0), "position"
    kind, number = header
    if kind not in STRIP_KINDS:
        raise Skip("strip kind 0x%02x isn't known yet; make one Assign & Map on this strip in MainStage" % kind)
    return (STRIP_KINDS[kind][0], number, 0), "header (%s %d)" % (STRIP_KINDS[kind][1], number)


def find_patches(bundle):
    out = {}
    root = os.path.join(bundle, "Concert.patch")
    for dirpath, _dirs, files in os.walk(root):
        if "data.plist" in files and dirpath != root:
            p = Patch(os.path.join(dirpath, "data.plist"))
            out.setdefault(p.name, p)
    return out


def write(assignments, src, dst, strips=None, dry_run=False, log=print, report=None):
    """Sync `dst` (a copy of `src`) with `assignments`. Returns (written, skipped); `report`, when given, also
    receives "repointed", "removed" and "kept"."""
    src, dst = os.path.abspath(src).rstrip("/"), os.path.abspath(dst).rstrip("/")
    if src == dst:
        raise SystemExit("refusing to write into the source concert")
    if os.path.exists(dst):
        raise SystemExit("%s already exists; pick a new name" % dst)
    if not dry_run:
        subprocess.run(["/usr/bin/ditto", src, dst], check=True)
    bundle = src if dry_run else dst

    layout = Layout(bundle)
    concert = Patch(os.path.join(bundle, "Concert.patch", "data.plist"))
    patches = find_patches(bundle)
    owners = layout.owners()
    taken = {k: name for k, (name, _auto) in owners.items()}
    ports = assignments["ports"]
    written, skipped, touched = [], [], set()
    repointed, removed, kept = [], [], []
    # Every address an assignment uses, whether or not it's written this run (another strip, a skip): only plugin-port
    # controls at none of these are stale.
    wanted = {(ports[r["port"]]["source"], r["channel"], r["cc"]) for s in assignments["strips"] for r in s["roles"]
              if (ports.get(r["port"]) or {}).get("source")}
    holders = [concert] + list(patches.values())

    def holder_of(identity_name):
        return next((p for p in holders if ("\x01IDENTITY:" + identity_name) in p.store), None)

    for strip in assignments["strips"]:
        if strips and strip["key"] not in strips:
            continue
        link = strip.get("mainStage") or {}
        if link.get("level") == "concert":
            patch = concert
        elif link.get("level") == "patch":
            patch = patches.get(link.get("patchName"))
        else:
            for row in strip["roles"]:
                skipped.append((strip, row, "not linked to a MainStage strip"))
            continue
        position, channel_info = patch.channel(link["stripName"]) if patch else (None, None)
        if channel_info is None:
            where = "the concert" if link.get("level") == "concert" else "patch %r" % link.get("patchName")
            for row in strip["roles"]:
                skipped.append((strip, row, "strip %r not found in %s" % (link.get("stripName"), where)))
            continue
        inst = channel_info["Channel_instID"]
        cst = os.path.join(os.path.dirname(patch.path), channel_info.get("Filename") or "")
        try:
            (ctype, cindex, calias), how = channel_id_for(patch, inst, position, cst)
        except Skip as e:
            for row in strip["roles"]:
                skipped.append((strip, row, str(e)))
            continue
        if how != "existing mapping":
            log("  note: %s's channel ID (type %d, index %d) comes from its %s" % (strip["name"], ctype, cindex, how))

        for row in strip["roles"]:
            try:
                port = ports.get(row["port"])
                if not port or not port.get("source"):
                    raise Skip("no CoreMIDI ID for port %r (start FOH Bridge once)" % row["port"])
                key = (port["source"], row["channel"], row["cc"])
                cls, param, slot, flipped, send_mute = target_of(row, channel_info, strip["key"])
            except Skip as e:
                skipped.append((strip, row, str(e)))
                continue
            want = (CLASS_OF[cls], param, slot, None if cls == "action" else inst, flipped)
            if key in taken:
                name, auto = owners.get(key, (taken[key], False))
                holder = holder_of(name)
                have = spec_of(holder.mapping_of(name)) if holder else None
                if have == want:
                    kept.append((strip, row, name))
                    continue
                if not auto or have is None or holder is not patch or cls == "action" or have[0] == CLASS_OF["action"]:
                    skipped.append((strip, row, "already assigned (%s)" % name))
                    continue
                # Same address, different target (the plugin moved slot, a binding changed): re-point the mapping.
                event = controller(port_dict(port["source"], row["port"], True), row["channel"], row["cc"], row.get("value") or 0, "event")
                chan = Obj("MAChannelID", ["MAChannelID", "NSObject"], {"aliasIndex": Ref(calias), "type": Ref(ctype), "index": Ref(cindex)})
                m = mapping(cls, inst=inst, chan=chan, param=param, slot=slot, flipped=flipped, send_mute=send_mute, event=event)
                patch.store["\x01IDENTITY:" + name] = encode({"root": ns_array([m])})
                if patch.table():
                    patch.table().replace(name, m)
                touched.add(patch.path)
                repointed.append((strip, row, cls, param, slot, name))
                continue

            value = row.get("value")
            if cls == "action":
                identity_name = str(uuid.uuid4()).upper()
                m = action_mapping(param)
                store_key = "\x01IDENTITY:" + identity_name
                patch.store[store_key] = encode({"root": ns_array([m])})
                patch.patch_mappings[store_key] = {"\x01NUMBER:0": encode({"root": m})}
                patch.ui[store_key] = ui_record(store_key)
                concert.ui[store_key] = ui_record(store_key)
                identity = Obj("WsPluginIdentity", None, {"uuidString": Ref(identity_name), "autogenerated": True})
                layout.add(identity, controller(port_dict(port["source"], row["port"], True), row["channel"], row["cc"], value or 0, "input"),
                           controller(port_dict(port["destination"], row["port"], False), row["channel"], row["cc"], 0, "output"))
                taken[key] = identity_name
                touched.add(patch.path)
                written.append((strip, row, cls, param, slot, identity_name, False))
                continue
            saved = saved_value_for(patch, cls, inst, slot, param, send_mute, flipped)
            if value is None:
                value = int(round(saved[1] * 127)) if saved else 0
            identity_name = str(uuid.uuid4()).upper()
            src_port = port_dict(port["source"], row["port"], True)
            dst_port = port_dict(port["destination"], row["port"], False)
            chan = Obj("MAChannelID", ["MAChannelID", "NSObject"], {"aliasIndex": Ref(calias), "type": Ref(ctype), "index": Ref(cindex)})
            event = controller(port_dict(port["source"], row["port"], True), row["channel"], row["cc"], value, "event")
            m = mapping(cls, inst=inst, chan=chan, param=param, slot=slot, flipped=flipped, send_mute=send_mute,
                        saved=saved, event=event)
            table = patch.table()
            if table:
                table.add(identity_name, m)
            store_key = "\x01IDENTITY:" + identity_name
            patch.store[store_key] = encode({"root": ns_array([m])})
            patch.ui[store_key] = ui_record(store_key)
            concert.ui[store_key] = ui_record(store_key)
            identity = Obj("WsPluginIdentity", None, {"uuidString": Ref(identity_name), "autogenerated": True})
            layout.add(identity, controller(src_port, row["channel"], row["cc"], value, "input"),
                       controller(dst_port, row["channel"], row["cc"], 0, "output"))
            taken[key] = identity_name
            touched.add(patch.path)
            written.append((strip, row, cls, param, slot, identity_name, saved is not None))

    # Hidden controls on the plugin ports that nothing wants any more. Only those: they're always ours.
    plugin_uids = {p["source"] for name, p in ports.items() if name.startswith(PLUGIN_PORT_PREFIX) and p.get("source")}
    for key, (name, auto) in owners.items():
        if key in wanted or not auto or key[0] not in plugin_uids:
            continue
        layout.remove(name)
        for p in holders:
            if ("\x01IDENTITY:" + name) in p.store or (p.table() and p.table().index_of(name) is not None):
                p.remove_identity(name)
                touched.add(p.path)
        concert.ui.pop("\x01IDENTITY:" + name, None)
        taken.pop(key, None)
        removed.append((key, name))

    if report is not None:
        report.update(repointed=repointed, removed=removed, kept=kept)
    if not dry_run:
        layout.save()
        for p in patches.values():
            if p.path in touched:
                dump_plist(p.path, p.plist)
                if p.table():
                    p.table().save()
        dump_plist(concert.path, concert.plist)
        if concert.path in touched and concert.table():
            concert.table().save()
    return written, skipped


def list_mappings(bundle):
    """Every hardware-assigned control in a concert, hand-made ones included, for FOH Bridge to learn from: the input
    address, what it drives (class, slot, parameter or action number) and on which strip (name, level, patch)."""
    layout = Layout(bundle)
    concert = Patch(os.path.join(bundle, "Concert.patch", "data.plist"))
    holders = [concert] + list(find_patches(bundle).values())
    out = []
    for (uid, ch, cc), (name, auto) in sorted(layout.owners().items(), key=lambda kv: (kv[0][0] or 0, kv[0][1] or 0, kv[0][2] or 0)):
        row = {"source": uid, "channel": ch, "cc": cc, "identity": name, "autogenerated": bool(auto)}
        holder = next((p for p in holders if ("\x01IDENTITY:" + name) in p.store), None)
        m = holder.mapping_of(name) if holder else None
        if m is not None:
            cls, param, slot, inst, flipped = spec_of(m)
            row.update({"class": cls, "parameter": param, "slot": slot, "flipped": flipped,
                        "position": slot + 1 if isinstance(slot, int) else None})   # slot is 0-based; inserts count from 1
            if inst is not None:
                strip = next((c.get("Channel_name") for c in holder.plist.get("channels", []) if c.get("Channel_instID") == inst), None)
                row.update({"strip": strip, "level": "concert" if holder is concert else "patch",
                            "patch": None if holder is concert else holder.name})
        out.append(row)
    return out


def sync_in_place(assignments, concert, backup_dir, keep=20, log=print):
    """Sync the concert itself: write a hidden sibling copy, move the original into `backup_dir` (that's the backup),
    and put the copy in its place. With nothing to change, nothing is touched. Returns the report dict."""
    concert = os.path.abspath(concert).rstrip("/")
    folder, base = os.path.dirname(concert), os.path.basename(concert)
    name = base[:-len(".concert")] if base.endswith(".concert") else base
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S-%f")[:-3]
    work = os.path.join(folder, ".%s.foh-sync-%s.concert" % (name, stamp))
    report = {}
    try:
        written, skipped = write(assignments, concert, work, log=log, report=report)
        report.update(written=written, skipped=skipped)
        if not (written or report["repointed"] or report["removed"]):
            shutil.rmtree(work)   # our own scratch copy
            report.update(changed=False, backup=None)
            return report
        os.makedirs(backup_dir, exist_ok=True)
        backup = os.path.join(backup_dir, "%s %s.concert" % (name, stamp))
        if os.path.exists(backup):
            raise SystemExit("%s already exists" % backup)
        # The swap can't be interrupted half-way (FOH Bridge stops a run that takes too long).
        blocked = signal.pthread_sigmask(signal.SIG_BLOCK, {signal.SIGTERM, signal.SIGINT})
        try:
            try:
                os.rename(concert, backup)
                moved_to = backup
            except OSError as e:
                if e.errno != errno.EXDEV:
                    raise
                # The backup folder is on another volume: copy the original there, and swap beside it.
                subprocess.run(["/usr/bin/ditto", concert, backup], check=True)
                moved_to = work + ".old"
                os.rename(concert, moved_to)
            try:
                os.rename(work, concert)
            except BaseException:
                os.rename(moved_to, concert)   # put the original back
                raise
            if moved_to != backup:
                shutil.rmtree(moved_to)   # identical to the backup just made
        finally:
            signal.pthread_sigmask(signal.SIG_SETMASK, blocked)
        report.update(changed=True, backup=backup)
    except BaseException:
        if os.path.exists(work):
            shutil.rmtree(work)   # our own scratch copy; the concert itself is untouched
        raise
    # Keep the newest `keep` backups of this concert (our own copies in our own folder).
    pattern = re.compile(re.escape(name) + r" \d{8}-\d{6}-\d{3}\.concert$")
    mine = sorted(f for f in os.listdir(backup_dir) if pattern.match(f))
    for old in mine[:-keep] if keep else []:
        shutil.rmtree(os.path.join(backup_dir, old))
    return report


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--assignments", help="JSON from `fohctl assignments --out`")
    ap.add_argument("--list-mappings", metavar="CONCERT", help="print every hardware-assigned control in CONCERT as JSON")
    ap.add_argument("--strips", help="comma-separated strip keys (default: every patch-level strip)")
    ap.add_argument("--dry-run", action="store_true", help="report only; don't copy or write anything")
    ap.add_argument("--report", help="also write the report as JSON")
    ap.add_argument("--in-place", metavar="CONCERT", help="sync this concert itself (needs --backup-dir; MainStage must be closed)")
    ap.add_argument("--backup-dir", help="where --in-place moves the previous version")
    ap.add_argument("src", nargs="?")
    ap.add_argument("dst", nargs="?")
    a = ap.parse_args(argv)
    if a.list_mappings:
        print(json.dumps(list_mappings(os.path.abspath(a.list_mappings).rstrip("/")), indent=1))
        return
    if not a.assignments:
        raise SystemExit("--assignments is required")
    with open(a.assignments) as f:
        assignments = json.load(f)
    if a.in_place:
        if not a.backup_dir:
            raise SystemExit("--in-place needs --backup-dir")
        signal.signal(signal.SIGTERM, lambda *_: sys.exit("stopped"))   # so a stopped run cleans up after itself
        r = sync_in_place(assignments, a.in_place, a.backup_dir)
        summary = {"changed": r["changed"], "backup": r["backup"], "written": len(r["written"]), "repointed": len(r["repointed"]),
                   "removed": len(r["removed"]), "kept": len(r["kept"]),
                   "skipped": [{"strip": s["key"], "role": row["role"], "reason": why} for s, row, why in r["skipped"]]}
        print(json.dumps(summary, indent=1))
        if a.report:
            with open(a.report, "w") as f:
                json.dump(summary, f, indent=1)
        return
    if not (a.src and a.dst):
        raise SystemExit("give SRC and DST, or --in-place CONCERT --backup-dir DIR")
    strips = set(a.strips.split(",")) if a.strips else None
    report = {}
    written, skipped = write(assignments, a.src, a.dst, strips, a.dry_run, report=report)

    print("\n%s %d assignments%s:" % ("Would write" if a.dry_run else "Wrote", len(written), "" if a.dry_run else " into " + a.dst))
    for strip, row, cls, param, slot, ident, had_saved in written:
        where = {"plugin": "%s › %s" % (row["pluginName"], row["parameterName"]),
                 "bypass": "%s bypass" % row["pluginName"],
                 "baseplate": row["parameterName"]}[cls]
        print("  %-10s %-16s %-13s ch %-2d CC %-3d → %s%s" % (strip["name"], row["role"], row["port"], row["channel"], row["cc"],
                                                             where, "" if had_saved else "  (no saved value)"))
    if report.get("repointed"):
        print("\nRe-pointed %d (same address, new target)." % len(report["repointed"]))
    if report.get("removed"):
        print("Removed %d stale plugin controls." % len(report["removed"]))
    if skipped:
        print("\nSkipped %d:" % len(skipped))
        for strip, row, why in skipped:
            print("  %-10s %-16s %s" % (strip["name"], row["role"], why))
    if a.report:
        with open(a.report, "w") as f:
            json.dump({"written": [{"strip": s["key"], "role": r["role"], "class": c, "param": p, "slot": sl, "identity": i}
                                   for s, r, c, p, sl, i, _ in written],
                       "skipped": [{"strip": s["key"], "role": r["role"], "reason": why} for s, r, why in skipped]},
                      f, indent=1)


if __name__ == "__main__":
    main()
