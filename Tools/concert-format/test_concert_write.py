class Sync(unittest.TestCase):
    """The writer is a sync: kept when matching, re-pointed when a plugin moved, removed when nothing wants it."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="concert-sync-")

    def tearDown(self):
        shutil.rmtree(self.tmp)

    def write(self, assignments, src, name):
        dst, report = os.path.join(self.tmp, name + ".concert"), {}
        written, skipped = cw.write(assignments, src, dst, log=quiet, report=report)
        return dst, written, skipped, report

    def test_stale_plugin_controls_are_removed_and_nothing_else(self):
        a, written, _, _ = self.write(plugin_assignments(MS_SAVED, {2: ["315", "316"]}), MS_SAVED, "A")
        stays, goes = written[0][5], written[1][5]
        b, again, _, report = self.write(plugin_assignments(MS_SAVED, {2: ["315"]}), a, "B")
        self.assertEqual(again, [])
        self.assertEqual([n for _k, n in report["removed"]], [goes])
        self.assertEqual([n for *_x, n in report["kept"]], [stays])
        self.assertEqual(registrations.registrations(b, goes), set(), "gone from every place it was registered")
        self.assertEqual(len(registrations.registrations(b, stays)), 10)
        for other in (MS_LMF, MS_MUTE):   # role-port and hand-made controls are never removed
            self.assertEqual(registrations.registrations(b, other), registrations.registrations(MS_SAVED, other))

    def test_strips_not_written_this_run_keep_their_plugin_controls(self):
        a, written, _, _ = self.write(plugin_assignments(MS_SAVED, {2: ["315"]}), MS_SAVED, "A")
        unlinked = plugin_assignments(MS_SAVED, {2: ["315"]}, strip_name="No such strip")
        b, _, skipped, report = self.write(unlinked, a, "B")
        self.assertTrue(skipped)
        self.assertEqual(report["removed"], [], "still assigned, just not found this run")

    def test_moved_plugin_is_re_pointed(self):
        a, written, _, _ = self.write(plugin_assignments(MS_SAVED, {2: ["315"]}), MS_SAVED, "A")
        ident = written[0][5]
        moved = plugin_assignments(MS_SAVED, {3: ["315"]})   # the same address; the plugin is now in slot 3
        b, again, _, report = self.write(moved, a, "B")
        self.assertEqual(again, [])
        self.assertEqual([r[5] for r in report["repointed"]], [ident])
        fresh, written_fresh, _, _ = self.write(moved, MS_SAVED, "Fresh")
        concert_b = cw.Patch(os.path.join(b, "Concert.patch/data.plist"))
        concert_f = cw.Patch(os.path.join(fresh, "Concert.patch/data.plist"))
        self.assertEqual(cw.spec_of(concert_b.mapping_of(ident)), cw.spec_of(concert_f.mapping_of(written_fresh[0][5])))
        self.assertEqual(cw.spec_of(concert_b.table().mapping(ident)), cw.spec_of(concert_b.mapping_of(ident)), "table agrees")
        self.assertEqual(len(registrations.registrations(b, ident)), 10)
        _c, _w, _s, third = self.write(moved, b, "C")
        self.assertEqual((len(third["kept"]), third["repointed"], third["removed"]), (1, [], []))

    def test_master_mute_is_kept_when_hand_made(self):
        """Church FOH Live 2's own Master Mute (FOH Global ch 1 CC 1) is the one the assignments want."""
        rows = [{"role": "mix.mute", "label": "Mute", "port": "FOH Global", "channel": 1, "cc": 1, "target": "mute",
                 "pluginPosition": 0, "pluginName": "Channel strip", "parameterID": "@mute", "parameterName": "Mute",
                 "kind": "toggle", "invert": False, "bus": None, "value": None}]
        master = {"show": "test", "ports": {"FOH Global": {"source": 1695955558, "destination": -1912009415}},
                  "strips": [{"key": "master/1", "name": "Master", "mainStage": {"level": "concert", "stripName": "Master"}, "roles": rows}]}
        (uid, _ch, _cc), = [k for k, (name, _auto) in cw.Layout(MS_SAVED).owners().items() if name == MS_MUTE]
        master["ports"]["FOH Global"]["source"] = uid
        _b, written, skipped, report = self.write(master, MS_SAVED, "B")
        self.assertEqual((written, skipped), ([], []))
        self.assertEqual([n for *_x, n in report["kept"]], [MS_MUTE])

    def test_in_place_backs_up_and_replaces(self):
        concert, backups = os.path.join(self.tmp, "Live.concert"), os.path.join(self.tmp, "backups")
        subprocess.run(["/usr/bin/ditto", MS_SAVED, concert], check=True)
        assignments = plugin_assignments(MS_SAVED, {2: ["315", "316"]})
        report = cw.sync_in_place(assignments, concert, backups, log=quiet)
        self.assertTrue(report["changed"])
        self.assertEqual(os.path.dirname(report["backup"]), backups)
        self.assertEqual(filecmp.dircmp(report["backup"], MS_SAVED).diff_files, [], "the backup is the original")
        for *_x, ident, _saved in report["written"]:
            self.assertEqual(len(registrations.registrations(concert, ident)), 10)
        self.assertEqual([f for f in os.listdir(self.tmp) if f.startswith(".")], [], "no scratch copy left behind")

        again = cw.sync_in_place(assignments, concert, backups, log=quiet)
        self.assertEqual((again["changed"], again["backup"]), (False, None))
        self.assertEqual(len(os.listdir(backups)), 1, "nothing to change, no new backup")
        self.assertEqual([f for f in os.listdir(self.tmp) if f.startswith(".")], [])

    def test_in_place_keeps_only_the_newest_backups(self):
        concert, backups = os.path.join(self.tmp, "Live.concert"), os.path.join(self.tmp, "backups")
        subprocess.run(["/usr/bin/ditto", MS_SAVED, concert], check=True)
        os.makedirs(os.path.join(backups, "Live copy 20200101-000000-000.concert"))   # another concert's backup
        for ids in (["315"], ["316"], ["315"], ["316"]):
            self.assertTrue(cw.sync_in_place(plugin_assignments(MS_SAVED, {2: ids}), concert, backups, keep=2, log=quiet)["changed"])
        names = os.listdir(backups)
        self.assertEqual(len(names), 3)
        self.assertIn("Live copy 20200101-000000-000.concert", names)

    def test_in_place_failure_leaves_the_concert_alone(self):
        concert, backups = os.path.join(self.tmp, "Live.concert"), os.path.join(self.tmp, "backups")
        subprocess.run(["/usr/bin/ditto", MS_SAVED, concert], check=True)
        with mock.patch.object(cw.Layout, "save", side_effect=OSError("disk full")):   # fails part-way through writing
            with self.assertRaises(OSError):
                cw.sync_in_place(plugin_assignments(MS_SAVED, {2: ["315"]}), concert, backups, log=quiet)
        self.assertEqual(filecmp.dircmp(concert, MS_SAVED).diff_files, [])
        self.assertEqual([f for f in os.listdir(self.tmp) if f.startswith(".")], [])
        self.assertFalse(os.path.exists(backups))


