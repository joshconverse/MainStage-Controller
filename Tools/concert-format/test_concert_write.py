    def test_nothing_else_changes(self):
        for dirpath, _dirs, files in os.walk(FIXTURE):
            for f in files:
                a = os.path.join(dirpath, f)
                b = os.path.join(self.dst, os.path.relpath(a, FIXTURE))
                if f in ("data.plist", "setupZ.layout"):
                    continue
                if f in ("Lead vox.cst", "Master.cst"):   # the patch's and the concert's mapping tables; every other chunk untouched
                    old_c, new_c = cw.ChannelStripFile(a).chunks, cw.ChannelStripFile(b).chunks
                    self.assertEqual(len(old_c), len(new_c))
                    for (oh, op), (nh, np_) in zip(old_c, new_c):
                        cid = int.from_bytes(oh[18:22], "little")
                        if cid in (cw.ChannelStripFile.MAPPINGS, cw.ChannelStripFile.LOOKUP):
                            self.assertEqual(oh[:28], nh[:28])
                            self.assertEqual(op[:16], np_[:16])
                        else:
                            self.assertEqual((oh, op), (nh, np_), cid)
                    continue
                self.assertTrue(filecmp.cmp(a, b, shallow=False), b)
        for path in plists(FIXTURE):
            old = cw.Patch(path)
            new = cw.Patch(os.path.join(self.dst, os.path.relpath(path, FIXTURE)))
            for key, blob in old.store.items():
                self.assertEqual(new.store[key], blob, key)
            for key, record in old.ui.items():
                self.assertEqual(new.ui[key], record, key)
            strip = lambda p: {k: v for k, v in p.plist["patch"]["engineNode"].items() if k not in ("parameterMappingMap", "uiPluginDataDict")}
            self.assertEqual(strip(old), strip(new), path)
            self.assertEqual(old.plist.get("channels"), new.plist.get("channels"), path)
        old_layout = decode(load_layout(FIXTURE))
        new_layout = decode(load_layout(self.dst))
        self.assertEqual(plain(old_layout["viewState"]), plain(new_layout["viewState"]))
        old_models = [plain(m) for m in old_layout["OnScreenObjects"]["PluginModels"]["NS.objects"]]
        new_models = [plain(m) for m in new_layout["OnScreenObjects"]["PluginModels"]["NS.objects"]]
        self.assertEqual(new_models[:len(old_models)], old_models)
        self.assertTrue(all(m["_class"] == "WsInvisibleScreenControl" for m in new_models[len(old_models):]))
        old_proxy, new_proxy = old_layout["proxyEngineNode"], new_layout["proxyEngineNode"]
        for key in old_proxy.fields:
            if key not in ("uiPluginDataDict", "parameterMappingMap"):
                self.assertEqual(plain(old_proxy[key]), plain(new_proxy[key]), key)

