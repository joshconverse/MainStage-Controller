def plists(bundle):
    """The concert's and every patch's data.plist (the bundle root's data.plist is window state)."""
    for dirpath, _dirs, files in os.walk(os.path.join(bundle, "Concert.patch")):
        for f in files:
            if f == "data.plist":
                yield os.path.join(dirpath, f)


def load_layout(bundle):
    return cw.Layout(bundle).archive


def quiet(*_args, **_kw):
    pass


def ident_name(k):
    """uuidString of a decoded WsPluginIdentity (stored as NSString or NSMutableString)."""
    name = plain(k).get("uuidString") if hasattr(k, "fields") else None
    return name.get("NS.string") if isinstance(name, dict) else name


def load_json(path):
    with open(path) as f:
        return json.load(f)


def plugin_assignments(bundle, positions, strip_name="Lead vox", cc_start=1):
    """Assignments with only plugin-port rows on one concert-level strip: {plugin position: [parameter IDs]}."""
    rows, cc = [], cc_start
    for position, ids in positions.items():
        for pid in ids:
            rows.append({"role": "plugin.%d.%s" % (position, pid), "label": pid, "port": "FOH Plugins 1", "channel": 1, "cc": cc,
                         "target": "plugin", "pluginPosition": position, "pluginName": "Pro-Q 3", "parameterID": pid,
                         "parameterName": pid, "kind": "continuous", "invert": False, "bus": None, "value": None})
            cc += 1
    return {"show": "test", "ports": {"FOH Plugins 1": PLUGIN_PORT_UIDS},
            "strips": [{"key": "in/1", "name": strip_name, "mainStage": {"level": "concert", "stripName": strip_name}, "roles": rows}]}


class RoundTrip(unittest.TestCase):
    def test_data_plists_survive_plistlib(self):
        for path in list(plists(FIXTURE)) + [os.path.join(FIXTURE, "data.plist")]:
            original = cw.load_plist(path)
            again = plistlib.loads(plistlib.dumps(original, fmt=plistlib.FMT_BINARY, sort_keys=False))
            self.assertEqual(original, again, path)

    def test_mapping_blobs_survive_the_codec(self):
        count = 0
        for path in plists(FIXTURE):
            store = cw.Patch(path).store
            for key, blob in store.items():
                tree = decode(plistlib.loads(blob))
                self.assertEqual(plain(tree), plain(decode(plistlib.loads(encode(tree)))), key)
                count += 1
        self.assertGreater(count, 20)

    def test_channel_strip_files_reassemble_byte_for_byte(self):
        count = 0
        for dirpath, _dirs, files in os.walk(FIXTURE):
            for f in files:
                if f.endswith(".cst"):
                    path = os.path.join(dirpath, f)
                    with open(path, "rb") as fh:
                        self.assertEqual(cw.ChannelStripFile(path).data(), fh.read(), path)
                    count += 1
        self.assertGreater(count, 5)

    def test_appending_leaves_the_layout_intact(self):
        archive = load_layout(FIXTURE)
        before = plain(decode(copy.deepcopy(archive)))
        enc = Encoder(archive["$objects"])
        enc.uid(Obj("WsPluginIdentity", None, {"uuidString": Ref("TEST"), "autogenerated": True}))
        self.assertEqual(before, plain(decode(archive)))


class MatchesMainStage(unittest.TestCase):
    """The writer's objects match what MainStage itself saves. The reference is a concert MainStage re-saved after the
    writer filled it (Church FOH Live 2), which also holds a hand-made Assign & Map (Master Mute)."""

    def setUp(self):
        self.concert = cw.Patch(os.path.join(MS_SAVED, "Concert.patch/data.plist"))
        self.real = self.concert.mapping_of(MS_LMF)

    def generated(self, event=None):
        f, c = self.real.fields, self.real["channelID"]
        chan = Obj("MAChannelID", ["MAChannelID", "NSObject"], {k: Ref(c[k].v) for k in ("aliasIndex", "type", "index")})
        saved = (f["kHasSavedValueKey"], f["kSavedValueFloatKey"], f["kSavedValueDoubleKey"])
        return cw.mapping("plugin", inst=f["kGInstIDKey"], chan=chan, param=20, slot=2, saved=saved,
                          event=event if event is not None else self.real["inputControlEvent"])

    def test_mapping_object(self):
        # MainStage saves the input event in its generic form (Assign & Map writes the learned one; both load), so the
        # event is taken from the reference; every other field, and its inline/reference encoding, must match.
        self.assertEqual(plain(self.real, strict=True), plain(self.generated(), strict=True))

    def test_mapping_blob_round_trips_through_plistlib(self):
        blob = cw.encode({"root": cw.ns_array([self.generated()])})
        again = decode(plistlib.loads(blob))["root"]["NS.objects"][0]
        self.assertEqual(plain(self.generated(), strict=True), plain(again, strict=True))

    def test_concert_mapping_table_lives_in_master_cst(self):
        table = self.concert.table()
        self.assertEqual(os.path.basename(table.cst.path), "Master.cst")
        actions = {k.replace("\x01IDENTITY:", "") for k in self.concert.patch_mappings}
        self.assertEqual(table.identities(), {k.replace("\x01IDENTITY:", "") for k in self.concert.store} - actions,
                         "everything but actions (Master Mute) is in the table")

    def test_layout_entries(self):
        tree = decode(load_layout(MS_SAVED))["HardwareSetup"]
        for kind, d in {"input": tree["controllerMapping"], "output": tree["outputControllerAssignment"]}.items():
            idx = [ident_name(k) for k in d["NS.keys"]].index(MS_LMF)
            want = plain(d["NS.objects"][idx], strict=True)
            port = cw.port_dict(1695955555 if kind == "input" else -1912009418, "FOH In 1-16", kind == "input")
            got = plain(cw.controller(port, 1, 26, want["value"], kind), strict=True)
            self.assertEqual(want, got, kind)

    def test_layout_registrations(self):
        """The four other places a hidden control lives in the layout (missing them, MainStage drops it)."""
        tree = decode(load_layout(MS_SAVED))
        hw, proxy = tree["HardwareSetup"], tree["proxyEngineNode"]

        def entry(d, name=MS_LMF):
            idx = [ident_name(k) for k in d["NS.keys"]].index(name)
            return d["NS.keys"][idx], d["NS.objects"][idx]

        def model(name):
            identity, _ = entry(hw["controllerMapping"], name)
            found = [m for m in tree["OnScreenObjects"]["PluginModels"]["NS.objects"] if m.fields.get("pluginIdentity") is identity]
            self.assertEqual(len(found), 1)
            return identity, found[0]

        # Assign & Map leaves controlName empty (as the writer does); a re-save fills in the factory's name. Both load.
        identity, made = model(MS_MUTE)
        self.assertEqual(plain(made, strict=True), plain(cw.invisible_control(identity, made["shelfUUID"]), strict=True))
        identity, resaved = model(MS_LMF)
        ours = cw.invisible_control(identity, resaved["shelfUUID"])
        ours.fields["controlName"] = Ref("WsInvisibleScreenControlFactory")
        self.assertEqual(plain(resaved, strict=True), plain(ours, strict=True))
        self.assertEqual(plain(entry(hw["globalSettings"])[1], strict=True), plain(cw.ns_dict([("outputEnabled", True)]), strict=True))
        self.assertEqual(plain(entry(proxy["uiPluginDataDict"])[1], strict=True), plain(cw.masked_dictionary(), strict=True))
        stored = entry(proxy["parameterMappingMap"]["storeDict"])[1]
        null = cw.null_mapping()
        null.fields["kHasSavedValueKey"] = True   # a saved value, which MainStage fills in when it saves
        self.assertEqual(plain(stored, strict=True), plain(cw.ns_array([null]), strict=True))
        # The null mapping is one object shared by every hardware-assigned control.
        other = entry(proxy["parameterMappingMap"]["storeDict"], MS_MUTE)[1]
        self.assertIs(other["NS.objects"][0], stored["NS.objects"][0])

    def test_master_mute_action_matches_the_hand_made_one(self):
        real = self.concert.mapping_of(MS_MUTE)
        self.assertEqual(plain(real, strict=True), plain(cw.action_mapping(cw.MASTER_MUTE_ACTION), strict=True))
        loose = decode(plistlib.loads(self.concert.patch_mappings["\x01IDENTITY:" + MS_MUTE]["\x01NUMBER:0"]))["root"]
        self.assertEqual(plain(loose, strict=True), plain(cw.action_mapping(cw.MASTER_MUTE_ACTION), strict=True),
                         "patchMappings holds the action itself, not wrapped in a list")


