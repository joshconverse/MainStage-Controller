class EndToEnd(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="concert-write-")
        self.dst = os.path.join(self.tmp, "Mapped.concert")
        self.assignments = load_json(ASSIGNMENTS)
        self.written, self.skipped = cw.write(self.assignments, FIXTURE, self.dst, log=quiet)

    def tearDown(self):
        shutil.rmtree(self.tmp)

    def test_counts(self):
        by_strip = {}
        for strip, *_ in self.written:
            by_strip[strip["key"]] = by_strip.get(strip["key"], 0) + 1
        # The fixture has no hardware assignments yet, so Lead vox's fader and LMF Gain are written too. At the
        # concert level: Botta Church and Main (fader, mute, solo, pan), and the Master's fader.
        self.assertEqual(by_strip, {"in/1": 48, "in/2": 35, "fx/1": 4, "out/1": 4, "master/1": 2}, "Master: fader and the Master Mute action")
        reasons = {why for _s, _r, why in self.skipped}
        self.assertTrue(any("0x44" in r for r in reasons), "Output 1/2 (kind 0x44) wait for an example")

    def test_every_hidden_control_is_registered_in_the_layout(self):
        tree = decode(load_layout(self.dst))
        hw, proxy = tree["HardwareSetup"], tree["proxyEngineNode"]
        idents = {ident for *_x, ident, _saved in self.written}

        def names(d):
            return [ident_name(k) for k in d["NS.keys"]]

        for label, d in (("inputs", hw["controllerMapping"]), ("outputs", hw["outputControllerAssignment"]),
                         ("settings", hw["globalSettings"]), ("proxy ui", proxy["uiPluginDataDict"]),
                         ("proxy store", proxy["parameterMappingMap"]["storeDict"])):
            self.assertLessEqual(idents, set(names(d)), label)
            self.assertEqual(len(names(d)), len(set(names(d))), label)
        models = tree["OnScreenObjects"]["PluginModels"]["NS.objects"]
        invisible = {ident_name(m["pluginIdentity"]): m for m in models if m.cls == "WsInvisibleScreenControl"}
        self.assertEqual(set(invisible), idents)
        shelves = {id(m.fields.get("shelfUUID")) for m in models}
        self.assertEqual(len(shelves), 1)          # all on the one shared shelf object
        store = proxy["parameterMappingMap"]["storeDict"]
        nulls = {id(v["NS.objects"][0]) for k, v in zip(store["NS.keys"], store["NS.objects"]) if ident_name(k) in idents}
        self.assertEqual(len(nulls), 1)            # one shared null mapping
        for d in (hw["controllerMapping"], hw["globalSettings"], proxy["uiPluginDataDict"], store):
            for k in d["NS.keys"]:
                name = ident_name(k)
                if name in idents:
                    self.assertIs(k, invisible[name]["pluginIdentity"])   # one identity object per control

    def test_every_assignment_is_wired_through(self):
        archive = load_layout(self.dst)
        hw = decode(archive)["HardwareSetup"]
        inputs = {plain(k)["uuidString"]: plain(v) for k, v in zip(hw["controllerMapping"]["NS.keys"], hw["controllerMapping"]["NS.objects"])}
        outputs = {plain(k)["uuidString"]: plain(v) for k, v in zip(hw["outputControllerAssignment"]["NS.keys"], hw["outputControllerAssignment"]["NS.objects"])}
        patch = cw.Patch(os.path.join(self.dst, "Concert.patch/Song One.patch/data.plist"))
        concert = cw.Patch(os.path.join(self.dst, "Concert.patch/data.plist"))
        ports = self.assignments["ports"]
        cst = cw.ChannelStripFile(os.path.join(self.dst, "Concert.patch/Song One.patch/Lead vox.cst"))
        lookup = decode(cst.archive(cw.ChannelStripFile.LOOKUP))["dictionary"]
        lookup = dict(zip([plain(k) for k in lookup["NS.keys"]], lookup["NS.objects"]))["IdentityIndexLookup"]
        cst_index = {plain(k)["uuidString"]: plain(v) for k, v in zip(lookup["NS.keys"], lookup["NS.objects"])}
        table = decode(cst.archive(cw.ChannelStripFile.MAPPINGS))["dictionary"]
        cst_mappings = dict(zip([plain(k) for k in table["NS.keys"]], table["NS.objects"]))
        self.assertEqual(len(cst_index), len(patch.store))
        self.assertEqual(sorted(cst_index.values()), sorted(cst_mappings))
        for strip, row, cls, param, slot, ident, _saved in self.written:
            if strip["mainStage"]["level"] != "patch":
                continue   # concert-level strips: see test_concert_level_strips
            src = inputs[ident]["MIDIPort"]["items"]
            dst = outputs[ident]["MIDIPort"]["items"]
            self.assertEqual((src["uniqueID"], src["isSource"]), (ports[row["port"]]["source"], True))
            self.assertEqual((dst["uniqueID"], dst["isSource"]), (ports[row["port"]]["destination"], False))
            self.assertEqual((inputs[ident]["channelID"], inputs[ident]["controllerID"], inputs[ident]["type"]), (row["channel"], row["cc"], 5))
            key = "\x01IDENTITY:" + ident
            m = decode(plistlib.loads(patch.store[key]))["root"]["NS.objects"][0]
            self.assertEqual(m.cls, {"plugin": "MAPlugInParameterMapping", "bypass": "MABypassParameterMapping",
                                     "baseplate": "MABaseplateParameterMapping"}[cls])
            self.assertEqual(m["parameterIndex_1"].v, param)
            self.assertEqual(m["kGInstIDKey"], 112 if strip["key"] == "in/1" else 116)
            self.assertEqual(m["channelID"]["index"].v, 1 if strip["key"] == "in/1" else 2)
            if cls != "baseplate":
                self.assertEqual(m["slot"].v, slot)
            self.assertIn(key, patch.ui)
            self.assertIn(key, concert.ui)
            self.assertEqual(plain(cst_mappings[cst_index[ident]]), plain(decode(plistlib.loads(patch.store[key]))["root"]), ident)

    def test_concert_level_strips(self):
        concert = cw.Patch(os.path.join(self.dst, "Concert.patch/data.plist"))
        table = cw.MappingTable(cw.ChannelStripFile(os.path.join(self.dst, "Concert.patch/Master.cst")))
        expected = {"fx/1": (100, 8, 0), "out/1": (88, 6, 0), "master/1": (92, 7, 0)}   # inst, MAChannelID type, index
        seen = set()
        for strip, row, cls, param, slot, ident, _saved in self.written:
            if strip["key"] not in expected or cls == "action":
                continue
            seen.add(strip["key"])
            m = decode(plistlib.loads(concert.store["\x01IDENTITY:" + ident]))["root"]["NS.objects"][0]
            inst, ctype, index = expected[strip["key"]]
            self.assertEqual((m["kGInstIDKey"], m["channelID"]["type"].v, m["channelID"]["index"].v), (inst, ctype, index), strip["key"])
            self.assertIn(ident, table.identities(), "concert-level mappings go in the concert's table (Master.cst)")
        self.assertEqual(seen, set(expected))

